#!/usr/bin/env python3
"""grouped_meta.cu -> grouped_mx.cu: GRP_FMT=1 MXFP4 x MXFP4 (E2M1, UE8M0/32), GRP_FMT=2 MXFP6 (E2M3 act) x
MXFP4 (E2M1 weight) -- the NVFP6 timing proxy (sm_120 has no E4M3-scaled FP6 MMA). Output SF (SFD) keeps the
example's UE4M3 epilogue, so its host/device buffers get their own type."""
s = open("grouped_meta.cu").read()
def rep(o, n, c=1):
    global s
    assert s.count(o) == c, (s.count(o), o[:60]); s = s.replace(o, n)
rep('using         ElementA    = cutlass::nv_float4_t<ElementInput>;             // Element type for A matrix operand',
    '''#if GRP_FMT == 1
using         ElementA    = cutlass::mx_float4_t<cutlass::float_e2m1_t>;
#else
using         ElementA    = cutlass::mx_float6_t<cutlass::float_e2m3_t>;
#endif''')
rep('constexpr int AlignmentA  = 32;                                             // Alignment of A matrix in units of elements (up to 16 bytes)',
    'constexpr int AlignmentA  = 128;')
rep('using         ElementB    = cutlass::nv_float4_t<ElementInput>;             // Element type for B matrix operand',
    'using         ElementB    = cutlass::mx_float4_t<cutlass::float_e2m1_t>;')
rep('constexpr int AlignmentB  = 32;                                             // Alignment of A matrix in units of elements (up to 16 bytes)',
    'constexpr int AlignmentB  = 128;')
rep('std::vector<HostTensorSF> block_SFD;', 'using HostTensorSFD = cutlass::HostTensor<ElementSFD, cutlass::layout::PackedVectorLayout>;\nstd::vector<HostTensorSFD> block_SFD;')
rep('std::vector<HostTensorSF> block_ref_SFD;', 'std::vector<HostTensorSFD> block_ref_SFD;')
rep('cutlass::DeviceAllocation<typename Gemm::GemmKernel::CollectiveMainloop::ElementSF *> ptr_SFD;', 'cutlass::DeviceAllocation<ElementSFD *> ptr_SFD;')
rep('    block_SFD.push_back(HostTensorSF(', '    block_SFD.push_back(HostTensorSFD(')
rep('    block_ref_SFD.push_back(HostTensorSF(', '    block_ref_SFD.push_back(HostTensorSFD(')
rep('  std::vector<typename Gemm::GemmKernel::CollectiveMainloop::ElementSF *> ptr_SFD_host(options.groups);',
    '  std::vector<ElementSFD *> ptr_SFD_host(options.groups);')
open("grouped_mx.cu", "w").write("// generated by make_grouped_mx.py\n" + s)
